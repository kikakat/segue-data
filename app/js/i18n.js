function t(s, vars) {
  // "tile|Finished": the part before | only tells the Spanish apart.
  let out = (LANG.ui === 'es' && ES[s] != null) ? ES[s] : s.replace(/^[a-z]+\|/, '');
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => vars[k] != null ? vars[k] : m);
  // "You gave it a 8.5" -> "an 8.5"
  if (LANG.ui !== 'es') out = out.replace(/\ba (?=8|11\b|18\b)/g, 'an ');
  return out;
}
