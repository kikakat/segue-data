/* Switches the interface language: category names, the tab bar and the
   bits of index.html that aren't redrawn. */
function setLang(l) {
  LANG.ui = l === 'es' ? 'es' : 'en';
  Object.keys(CATS).forEach(c => Object.assign(CATS[c], LANG.ui === 'es' ? CAT_ES[c] : CAT_EN[c]));
  document.documentElement.lang = LANG.ui;
  $$('[data-t]').forEach(el => { el.textContent = t(el.dataset.t); });
  $$('[data-t-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.tLabel)); });
  $('#splash').textContent = LANG.ui === 'es' ? 'Abriendo Segue…' : 'Opening Segue…';
}
